/** Connect lazily and create tables once. */
export async function initDb(): Promise<void> {
  if (_ready) return _ready;
  // On failure, reset so the next caller retries instead of every request
  // inheriting a permanently-rejected promise (the exact failure mode that made
  // /api/health 500 forever after one bad cold start).
  _ready = (async () => {
    const url = Deno.env.get("DATABASE_URL");
    if (!url) throw new Error("DATABASE_URL not set (assign a database in Deno Deploy)");

    _sql = postgres(url, {
      max: 5,
      idle_timeout: 20,
      connect_timeout: 15,
      prepare: false, // pooler in front of Prisma Postgres rejects named prepared statements
      onnotice: () => {}, // "relation already exists, skipping" on every cold start is noise
    });

    // Run each DDL statement on its own: some Postgres poolers reject
    // multi-statement simple queries, and per-statement errors are precise.
    // (The schema contains no `;` inside string literals, so this split is safe.)
    for (const raw of SCHEMA_SQL.split(";")) {
      const stmt = raw.trim();
      if (!stmt) continue;
      try {
        await _sql.unsafe(stmt);
      } catch (e) {
        const summary = stmt.replace(/\s+/g, " ").slice(0, 90);
        const msg = e instanceof Error ? e.message : String(e);
        throw new Error(`schema statement failed [${summary}]: ${msg}`);
      }
    }

    // Widen millisecond-epoch columns created before they were BIGINT. The
    // original DDL copied SQLite's `INTEGER` (64-bit), but Postgres `INTEGER`
    // is 32-bit, so any ms timestamp (~1.7e12) overflowed and every INSERT
    // failed. `CREATE TABLE IF NOT EXISTS` never alters an existing column, so
    // these idempotent ALTERs are required on already-provisioned databases.
    for (const stmt of MIGRATIONS) {
      try {
        await _sql.unsafe(stmt);
      } catch (e) {
        const msg = e instanceof Error ? e.message : String(e);
        throw new Error(`migration failed [${stmt}]: ${msg}`);
      }
    }

    // Seed the shipped curated catalog once per empty table. SmartRouter scores
    // and fusion panel tool-gating read `models`; with an empty table metrics
    // silently fall back to defaults. Idempotent: only touches empty tables,
    // never overwrites user edits or discovery results.
    try {
      await seedCuratedCatalog(_sql);
    } catch (e) {
      // Seed failure must not take the whole DB down — worst case the catalog
      // just stays empty and the next cold start retries.
      console.error("[openllm] catalog seed failed:", e);
    }
  })().catch((e) => {
    _ready = null;
    _sql = null;
    throw e;
  });
  return _ready;
}

/** Get the query tag. Always `await initDb()` first. */
async function db(): Promise<Sql | null> {
  if (!Deno.env.get("DATABASE_URL")) return null;
  await initDb();
  return _sql;
}

/** Execute a raw SQL query (template literal). Returns rows array. */
export async function query(strings: TemplateStringsArray, ...values: any[]): Promise<any[]> {
  const sql = await db();
  if (!sql) return [];
  // @ts-ignore: postgres.js template literal
  const rows = await sql(strings, ...values);
  return rows;
}

