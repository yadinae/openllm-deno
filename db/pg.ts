export async function getSessionUser(tokenHash: string): Promise<{ userId: number; email: string } | null> {
  const sql = await db();
  if (!sql) return null;
  const rows = await sql`
    SELECT s.user_id, s.expires_at_ms, u.email
    FROM sessions s JOIN users u ON u.id = s.user_id
    WHERE s.token_hash = ${tokenHash}
  `;
  if (!rows.length) return null;
  const r = rows[0];
  if (Number(r.expires_at_ms) <= Date.now()) {
    await sql`DELETE FROM sessions WHERE token_hash = ${tokenHash}`;
    return null;
  }
  return { userId: Number(r.user_id), email: String(r.email) };
}

