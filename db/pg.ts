export async function pingDb(): Promise<{ ok: boolean; detail: string }> {
  try {
    const sql = await db();
    if (!sql) return { ok: false, detail: "No database" };
    // @ts-ignore: postgres.js template literal type issue
    const one = await sql`SELECT 1 AS one, current_database() AS db`;
    const keys = await sql`SELECT count(*)::int AS n FROM api_keys`;
    const models = await sql`SELECT count(*)::int AS n FROM discovered_models`;
    const settings = await sql`SELECT count(*)::int AS n FROM settings`;
    return {
      ok: Number(one[0]?.one) === 1,
      detail: `db=${one[0]?.db} api_keys=${keys[0]?.n} models=${models[0]?.n} settings=${settings[0]?.n}`,
    };
  } catch (e) {
    return { ok: false, detail: e instanceof Error ? `${e.name}: ${e.message}` : String(e) };
  }
}

// ---------------- Curated catalog seed ----------------
//
// FreeLLMAPI ships a curated model catalog (rankings, rate limits, tool/vision
// capability, paid pricing) that discovery cannot produce. The JSON files under
// db/seed/ are an export of that catalog. They are inserted only when the
// target table is empty, so user edits and live discovery are never overwritten.

type SqlClient = any;

async function readSeedJson<T>(name: string): Promise<T[]> {
  const url = new URL(`./seed/${name}`, import.meta.url);
  const text = await Deno.readTextFile(url);
  return JSON.parse(text) as T[];
}

/** Insert rows in chunks with a single multi-row INSERT per chunk. */
async function insertRows(
  sql: SqlClient,
  table: string,
  columns: string[],
  rows: unknown[][],
): Promise<number> {
  let inserted = 0;
  const CHUNK = 100;
  for (let i = 0; i < rows.length; i += CHUNK) {
    const chunk = rows.slice(i, i + CHUNK).map((r) => r.map((v) => (v === undefined ? null : v)));
    const tuples = chunk
      .map((_, ri) => `(${columns.map((_, ci) => `$${ri * columns.length + ci + 1}`).join(",")})`)
      .join(",");
    const flat = chunk.flat();
    await sql.unsafe(
      `INSERT INTO ${table} (${columns.join(",")}) VALUES ${tuples} ON CONFLICT DO NOTHING`,
      flat,
    );
    inserted += chunk.length;
  }
  return inserted;
}

async function tableIsEmpty(sql: SqlClient, table: string): Promise<boolean> {
  const rows = await sql.unsafe(`SELECT 1 FROM ${table} LIMIT 1`);
  return rows.length === 0;
}

/** Seed models / embedding_models / media_models / quirks from db/seed/*.json.
 * Runs inside initDb after migrations; safe on every cold start. */
export async function seedCuratedCatalog(sql: SqlClient): Promise<void> {
  const log = (t: string, n: number) => console.log(`[openllm] catalog seed: ${t} += ${n}`);

  if (await tableIsEmpty(sql, "models")) {
    const rows = await readSeedJson<Record<string, unknown>>("models.json");
    const n = await insertRows(
      sql,
      "models",
      [
        "platform", "model_id", "display_name", "intelligence_rank", "speed_rank",
        "size_label", "rpm_limit", "rpd_limit", "tpm_limit", "tpd_limit",
        "monthly_token_budget", "context_window", "enabled", "supports_vision",
        "supports_tools", "paid_input_per_m", "paid_output_per_m", "source",
      ],
      rows.map((m) => [
        m.platform, m.model_id, m.display_name,
        Number(m.intelligence_rank) || 0, Number(m.speed_rank) || 0,
        m.size_label ?? "", m.rpm_limit ?? null, m.rpd_limit ?? null,
        m.tpm_limit ?? null, m.tpd_limit ?? null,
        m.monthly_token_budget ?? "", m.context_window ?? null,
        Number(m.enabled ?? 1), Number(m.supports_vision ?? 0),
        Number(m.supports_tools ?? 0),
        m.paid_input_per_m == null ? null : Number(m.paid_input_per_m),
        m.paid_output_per_m == null ? null : Number(m.paid_output_per_m),
        m.source ?? "catalog",
      ]),
    );
    log("models", n);
  }

  if (await tableIsEmpty(sql, "embedding_models")) {
    const rows = await readSeedJson<Record<string, unknown>>("embedding_models.json");
    const n = await insertRows(
      sql,
      "embedding_models",
      ["family", "platform", "model_id", "display_name", "dimensions", "max_input_tokens", "priority", "enabled", "quota_label"],
      rows.map((m) => [
        m.family, m.platform, m.model_id, m.display_name,
        Number(m.dimensions) || 0, m.max_input_tokens ?? null,
        Number(m.priority) || 0, Number(m.enabled ?? 1), m.quota_label ?? "",
      ]),
    );
    log("embedding_models", n);
  }

  if (await tableIsEmpty(sql, "media_models")) {
    const rows = await readSeedJson<Record<string, unknown>>("media_models.json");
    const n = await insertRows(
      sql,
      "media_models",
      ["platform", "model_id", "display_name", "modality", "priority", "enabled", "quota_label", "meta_json"],
      rows.map((m) => [
        m.platform, m.model_id, m.display_name, m.modality,
        Number(m.priority) || 0, Number(m.enabled ?? 1), m.quota_label ?? "",
        m.meta_json == null ? null : String(m.meta_json),
      ]),
    );
    log("media_models", n);
  }

  if (await tableIsEmpty(sql, "quirks")) {
    const rows = await readSeedJson<Record<string, unknown>>("quirks.json");
    for (const q of rows) {
      const ins = await sql.unsafe(
        `INSERT INTO quirks (slug, title, body, severity, created_at_ms, updated_at_ms)
         VALUES ($1,$2,$3,$4,$5,$6) ON CONFLICT (slug) DO NOTHING RETURNING id`,
        [q.slug, q.title, q.body ?? "", q.severity ?? "info",
         Number(q.created_at_ms) || 0, Number(q.updated_at_ms) || 0],
      );
      const quirkId = ins[0]?.id;
      if (quirkId == null) continue;
      const targets = (q.targets ?? []) as Array<{ platform?: string | null; model_glob?: string | null }>;
      for (const t of targets) {
        await sql.unsafe(
          `INSERT INTO quirk_targets (quirk_id, platform, model_glob) VALUES ($1,$2,$3)`,
          [quirkId, t.platform ?? null, t.model_glob ?? null],
        );
      }
    }
    log("quirks", rows.length);
  }
}
